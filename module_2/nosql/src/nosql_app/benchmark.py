from __future__ import annotations

import csv
import json
import random
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from statistics import mean

import matplotlib.pyplot as plt
import typer
from bson import ObjectId

from nosql_app.config import DEFAULT_DB_NAME, DEFAULT_MONGO_URI
from nosql_app.db import create_client
from nosql_app.json_utils import to_jsonable
from nosql_app.queries import student_average, student_grades, top_students


app = typer.Typer(help="Benchmark utility for standalone and sharded MongoDB deployments")


class Profile(StrEnum):
    read_heavy = "read-heavy"
    mixed = "mixed"
    write_heavy = "write-heavy"


@dataclass(slots=True)
class OperationResult:
    scenario: str
    latency_ms: float
    success: bool
    error: str | None
    timestamp: str


def _choose_scenario(profile: Profile) -> str:
    if profile == Profile.read_heavy:
        scenarios = ["student_grades", "student_average", "top_students", "insert_grade"]
        weights = [0.45, 0.3, 0.2, 0.05]
    elif profile == Profile.write_heavy:
        scenarios = ["student_grades", "student_average", "top_students", "insert_grade"]
        weights = [0.2, 0.15, 0.15, 0.5]
    else:
        scenarios = ["student_grades", "student_average", "top_students", "insert_grade"]
        weights = [0.35, 0.2, 0.2, 0.25]
    return random.choices(scenarios, weights=weights, k=1)[0]


def _percentile(values: list[float], percentile: float) -> float:
    if not values:
        return 0.0
    sorted_values = sorted(values)
    index = max(0, min(len(sorted_values) - 1, round((len(sorted_values) - 1) * percentile)))
    return sorted_values[index]


def _prepare_identifiers(database) -> tuple[list[str], list[str]]:
    students = [item["studentId"] for item in database.students.find({}, {"studentId": 1}).limit(250)]
    courses = [item["courseCode"] for item in database.courses.find({}, {"courseCode": 1}).limit(250)]
    if not students or not courses:
        raise RuntimeError("Benchmark requires seeded students and courses collections")
    return students, courses


def _run_scenario(database, scenario: str, students: list[str], courses: list[str]) -> None:
    if scenario == "student_grades":
        student_grades(database, random.choice(students), limit=10)
        return
    if scenario == "student_average":
        student_average(database, random.choice(students))
        return
    if scenario == "top_students":
        top_students(database, random.choice(courses), limit=10)
        return

    database.grades.insert_one(
        {
            "studentId": ObjectId(),
            "courseId": ObjectId(),
            "grade": round(random.uniform(3.0, 5.0), 2),
            "gradeType": "benchmark",
            "gradeDate": datetime.now(UTC),
            "notes": "Generated by benchmark",
            "status": "final",
            "teacher": ObjectId(),
        }
    )


def _write_csv(path: Path, results: list[OperationResult]) -> None:
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=["timestamp", "scenario", "latency_ms", "success", "error"])
        writer.writeheader()
        for result in results:
            writer.writerow(
                {
                    "timestamp": result.timestamp,
                    "scenario": result.scenario,
                    "latency_ms": round(result.latency_ms, 3),
                    "success": result.success,
                    "error": result.error or "",
                }
            )


def _write_json(path: Path, payload: dict) -> None:
    with path.open("w", encoding="utf-8") as file:
        json.dump(to_jsonable(payload), file, ensure_ascii=False, indent=2)


def _plot_latency(path: Path, summary: dict[str, dict[str, float]]) -> None:
    scenarios = list(summary.keys())
    p50_values = [summary[scenario]["p50_ms"] for scenario in scenarios]
    p95_values = [summary[scenario]["p95_ms"] for scenario in scenarios]
    positions = range(len(scenarios))

    plt.figure(figsize=(10, 5))
    plt.bar(positions, p50_values, width=0.4, label="p50", align="edge")
    plt.bar([position + 0.4 for position in positions], p95_values, width=0.4, label="p95", align="edge")
    plt.xticks([position + 0.2 for position in positions], scenarios, rotation=20)
    plt.ylabel("Latency, ms")
    plt.title("MongoDB benchmark latency")
    plt.legend()
    plt.tight_layout()
    plt.savefig(path)
    plt.close()


def _plot_throughput(path: Path, summary: dict[str, dict[str, float]]) -> None:
    scenarios = list(summary.keys())
    throughput_values = [summary[scenario]["throughput_ops_sec"] for scenario in scenarios]

    plt.figure(figsize=(10, 5))
    plt.bar(scenarios, throughput_values)
    plt.ylabel("Operations / sec")
    plt.title("MongoDB benchmark throughput")
    plt.xticks(rotation=20)
    plt.tight_layout()
    plt.savefig(path)
    plt.close()


def _summarize(results: list[OperationResult], duration_seconds: int) -> dict[str, dict[str, float]]:
    summary: dict[str, dict[str, float]] = {}
    scenarios = sorted({result.scenario for result in results})
    for scenario in scenarios:
        scenario_results = [result for result in results if result.scenario == scenario]
        latencies = [result.latency_ms for result in scenario_results]
        success_count = sum(1 for result in scenario_results if result.success)
        total = len(scenario_results)
        summary[scenario] = {
            "operations": total,
            "success_rate": round(success_count / total, 4) if total else 0.0,
            "avg_latency_ms": round(mean(latencies), 3) if latencies else 0.0,
            "p50_ms": round(_percentile(latencies, 0.5), 3) if latencies else 0.0,
            "p95_ms": round(_percentile(latencies, 0.95), 3) if latencies else 0.0,
            "throughput_ops_sec": round(total / duration_seconds, 3) if duration_seconds else 0.0,
        }
    return summary


@app.command()
def run_benchmark(
    target_uri: str = typer.Option(DEFAULT_MONGO_URI, "--target-uri"),
    db_name: str = typer.Option(DEFAULT_DB_NAME, "--db-name"),
    label: str = typer.Option("benchmark", "--label"),
    duration_seconds: int = typer.Option(30, "--duration-seconds", min=1),
    workers: int = typer.Option(8, "--workers", min=1, max=128),
    profile: Profile = typer.Option(Profile.mixed, "--profile"),
    output_dir: Path = typer.Option(Path("benchmark_results"), "--output-dir"),
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    client = create_client(target_uri)
    database = client[db_name]
    client.admin.command("ping")
    students, courses = _prepare_identifiers(database)

    deadline = time.monotonic() + duration_seconds
    all_results: list[OperationResult] = []

    def worker() -> list[OperationResult]:
        worker_results: list[OperationResult] = []
        while time.monotonic() < deadline:
            scenario = _choose_scenario(profile)
            started = time.perf_counter()
            error_message = None
            success = True
            try:
                _run_scenario(database, scenario, students, courses)
            except Exception as error:  # noqa: BLE001
                success = False
                error_message = str(error)
            latency_ms = (time.perf_counter() - started) * 1000
            worker_results.append(
                OperationResult(
                    scenario=scenario,
                    latency_ms=latency_ms,
                    success=success,
                    error=error_message,
                    timestamp=datetime.now(UTC).isoformat(),
                )
            )
        return worker_results

    with ThreadPoolExecutor(max_workers=workers) as executor:
        for worker_results in executor.map(lambda _: worker(), range(workers)):
            all_results.extend(worker_results)

    client.close()

    summary = _summarize(all_results, duration_seconds)
    base_name = f"{label}_{profile.value}_{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}"
    csv_path = output_dir / f"{base_name}.csv"
    json_path = output_dir / f"{base_name}.json"
    latency_plot = output_dir / f"{base_name}_latency.png"
    throughput_plot = output_dir / f"{base_name}_throughput.png"

    _write_csv(csv_path, all_results)
    _write_json(
        json_path,
        {
            "label": label,
            "target_uri": target_uri,
            "db_name": db_name,
            "duration_seconds": duration_seconds,
            "workers": workers,
            "profile": profile.value,
            "summary": summary,
        },
    )
    _plot_latency(latency_plot, summary)
    _plot_throughput(throughput_plot, summary)

    typer.echo(json.dumps({"summary": summary, "csv": str(csv_path), "json": str(json_path)}, ensure_ascii=False, indent=2))


def run() -> None:
    app()


if __name__ == "__main__":
    run()

