// Длина Московской кольцевой автомобильной дороги — 109 километров. Байкер Вася стартует с
// нулевого километра МКАД и едет со скоростью v километров в час. На какой отметке он
// остановится через t часов?
// Формат ввода: v t (целые, в диапазоне [-1000, 1000]).
// Формат вывода: целое число от 0 до 108 — номер отметки.

#include <bits/stdc++.h>
using namespace std;

int main() {
	long long v, t;
	if (!(cin >> v >> t)) return 0;
	const int L = 109;
	long long dist = v * t; // может быть отрицательным
	int pos = (int)((dist % L + L) % L); // приводим к [0, 108]
	cout << pos << '\n';
	return 0;
}

